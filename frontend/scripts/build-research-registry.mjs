#!/usr/bin/env node
// Build-time registry of the file-based research articles.
//
// WHY: lib/mdx.js used to read content/research/*.mdx with `fs` on every
// request. Cloudflare Workers have no project filesystem, so on Workers the
// research hub listed none of these articles and every article page was a
// 404. This script reads the same files at BUILD time and writes them into a
// JavaScript module the bundler includes, so lib/mdx.js can serve the same
// articles with no filesystem at runtime — on Vercel and on Workers alike.
//
// WHAT IT PRESERVES: every .mdx file, published or not. Frontmatter is passed
// through exactly as gray-matter parses it (a YAML date stays a Date) and the
// body is passed through untouched. Visibility — `published: false` hiding an
// article unless drafts are asked for — is still decided in lib/mdx.js, by the
// same code as before. Nothing here rewrites or copies content into Git: the
// output is a gitignored build artifact, regenerated by next.config.js at the
// start of every `next build` and `next dev` — whatever command invokes them.
//
//   node scripts/build-research-registry.mjs            # writes lib/generated/
//   node scripts/build-research-registry.mjs --out FILE # anywhere (tests)
//   ... --content DIR                                    # other sources (tests)

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const arg = (name) => {
  const i = process.argv.indexOf(name);
  return i > -1 ? path.resolve(process.argv[i + 1]) : null;
};
const CONTENT_DIR = arg("--content") || path.join(ROOT, "content", "research");
const outArg = process.argv.indexOf("--out");
const OUT = outArg > -1 ? path.resolve(process.argv[outArg + 1]) : path.join(ROOT, "lib", "generated", "research-registry.js");

function readArticles() {
  if (!fs.existsSync(CONTENT_DIR)) return [];
  return fs
    .readdirSync(CONTENT_DIR)
    .filter((f) => f.endsWith(".mdx"))
    .sort()
    .map((file) => {
      const raw = fs.readFileSync(path.join(CONTENT_DIR, file), "utf-8");
      const { data, content } = matter(raw);
      return { slug: file.replace(/\.mdx$/, ""), data, content };
    });
}

// JSON cannot carry a Date. Mark them, then emit real `new Date(...)` calls so
// a value that was a Date when read from disk is still a Date at runtime.
function toModuleSource(articles) {
  const DATE = "__vwDate__";
  const json = JSON.stringify(
    articles,
    function replacer(key, value) {
      const original = this[key];
      return original instanceof Date ? { [DATE]: original.toISOString() } : value;
    },
    2
  );
  const body = json.replace(
    new RegExp(`\\{\\s*"${DATE}":\\s*("[^"]*")\\s*\\}`, "g"),
    (_, iso) => `new Date(${iso})`
  );
  return [
    "// GENERATED by scripts/build-research-registry.mjs from content/research/*.mdx.",
    "// Do not edit and do not commit — it is rebuilt by `npm run build` and `npm run dev`.",
    `export default ${body};`,
    "",
  ].join("\n");
}

const articles = readArticles();
fs.mkdirSync(path.dirname(OUT), { recursive: true });
// Write-then-rename, so a build worker reading the registry never sees half a
// file: next.config.js runs this in every process that loads the config.
const tmp = `${OUT}.${process.pid}.tmp`;
fs.writeFileSync(tmp, toModuleSource(articles));
fs.renameSync(tmp, OUT);
console.log(`research registry: ${articles.length} article(s) -> ${path.relative(process.cwd(), OUT)}`);

PROVENANCE = {"data_source", "source_url", "collection_date",
              "confidence_score", "verification_status", "notes"}


def rows_of(name):
    with open(DATASETS / name, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def classify(name, col, values):
    """Infer a column's type and observed domain from its actual values."""
    nonpv = [v for v in values if v != PV]
    pv_n = len(values) - len(nonpv)
    distinct = sorted(set(nonpv))

    if col.endswith("_id") or col == "mapping_id":
        kind = "identifier"
        domain = f"{len(distinct)} distinct"
    elif all(v.replace(".", "", 1).isdigit() for v in nonpv) and nonpv:
        kind = "numeric"
        nums = [float(v) for v in nonpv]
        lo, hi = min(nums), max(nums)
        fmt = (lambda x: f"{x:g}")
        domain = f"{fmt(lo)}–{fmt(hi)}"
    elif len(distinct) <= 8 and nonpv:
        kind = "enum"
        domain = ", ".join(f"`{v}`" for v in distinct)
    elif col in ("source_url",):
        kind = "url"
        domain = f"{len(distinct)} distinct"
    elif col == "collection_date":
        kind = "date"
        domain = ", ".join(f"`{v}`" for v in distinct)
    else:
        kind = "text"
        domain = f"{len(distinct)} distinct values"

    if pv_n:
        domain += f" · **{pv_n} sentinel**"
    return kind, domain



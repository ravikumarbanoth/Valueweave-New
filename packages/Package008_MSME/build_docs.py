def rows_of(name):
    with open(DATASETS / name, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def classify(col, values):
    nonpv = [v for v in values if v != PV]
    pv_n = len(values) - len(nonpv)
    distinct = sorted(set(nonpv))
    if col.endswith("_id") or col.endswith("_ids"):
        kind, domain = "identifier", f"{len(distinct)} distinct"
    elif nonpv and all(v.replace(".", "", 1).isdigit() for v in nonpv):
        nums = [float(v) for v in nonpv]
        kind, domain = "numeric", f"{min(nums):g}-{max(nums):g}"
    elif nonpv and len(distinct) <= 9:
        kind, domain = "enum", ", ".join(f"`{v}`" for v in distinct)
    elif col in ("source_url", "official_portal", "official_website"):
        kind, domain = "url", f"{len(distinct)} distinct"
    elif col == "collection_date":
        kind, domain = "date", ", ".join(f"`{v}`" for v in distinct)
    else:
        kind, domain = "text", f"{len(distinct)} distinct values"
    if pv_n:
        domain += f" · **{pv_n} sentinel**"
    return kind, domain


